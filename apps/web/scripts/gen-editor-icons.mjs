#!/usr/bin/env node
/**
 * Generates the editor's icons from Phosphor's Bold set (@phosphor-icons/core,
 * MIT), the same vendoring approach as gen-tool-icons.mjs (path data only, nothing at runtime).
 *
 *   node scripts/gen-editor-icons.mjs   → src/tools/editor/icons.tsx (committed)
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgDir = join(here, "..", "node_modules", "@phosphor-icons", "core");
const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
const license = readFileSync(join(pkgDir, "LICENSE"), "utf8").trim();

/** Export name → Phosphor name (bold weight). */
const ICONS = {
  UndoBold: "arrow-u-up-left",
  RedoBold: "arrow-u-up-right",
  DownloadBold: "download-simple",
  CloseBold: "x",
  FileUpBold: "file-arrow-up",
  PencilBold: "pencil-simple",
  SelectBold: "cursor",
  EditTextBold: "text-aa",
  TextBold: "text-t",
  SignBold: "signature",
  MarkBold: "highlighter-circle",
  DrawBold: "scribble-loop",
  ShapesBold: "shapes",
  ImageBold: "image",
  WhiteoutBold: "eraser",
  CaretDownBold: "caret-down",
  CaretLeftBold: "caret-left",
  CaretRightBold: "caret-right",
  MinusBold: "minus",
  PlusBold: "plus",
  FitBold: "arrows-out",
  RotateLeftBold: "arrow-counter-clockwise",
  RotateRightBold: "arrow-clockwise",
  CopyBold: "copy",
  FilePlusBold: "file-plus",
  TrashBold: "trash",
  PanelBold: "sidebar-simple",
  MoreBold: "dots-three",
  ShieldBold: "shield-check",
  SavedBold: "check-circle",
  WarningBold: "warning",
  BoldBold: "text-b",
  ItalicBold: "text-italic",
  UnderlineBold: "text-underline",
  AlignLeftBold: "text-align-left",
  AlignCenterBold: "text-align-center",
  AlignRightBold: "text-align-right",
  SquareBold: "square",
  CircleBold: "circle",
  LineBold: "line-segment",
  ArrowBold: "arrow-up-right",
  HighlightBold: "highlighter",
  StrikeBold: "text-strikethrough",
  EyeBold: "eye",
  EyeSlashBold: "eye-slash",
  HistoryBold: "clock-counter-clockwise",
  KeyboardBold: "keyboard",
  BroomBold: "broom",
  ForwardBold: "selection-foreground",
  BackwardBold: "selection-background",
  EyedropperBold: "eyedropper",
  ListBold: "list-bullets",
  PagesBold: "squares-four",
  CheckBold: "check",
  UploadBold: "upload-simple",
  PenBold: "pen-nib",
  MarkerBold: "marker-circle",
  LockBold: "lock-simple",
  FileBold: "file",
  InfoBold: "info",
  PaintBold: "paint-bucket",
};

const body = Object.entries(ICONS)
  .map(([exportName, name]) => {
    const svg = readFileSync(join(pkgDir, "assets", "bold", `${name}-bold.svg`), "utf8");
    const inner = svg.replace(/^<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").replace(/\/>/g, " />");
    return `/** Phosphor "${name}" (bold). */\nexport const ${exportName} = (p: IconProps) => <Icon {...p}>${inner}</Icon>;\n`;
  })
  .join("\n");

const out = `/*
 * GENERATED by scripts/gen-editor-icons.mjs from @phosphor-icons/core ${pkg.version} (Bold). Do not edit.
 *
 * Icons: Phosphor Icons (https://phosphoricons.com). License notice, as shipped in @phosphor-icons/core:
 *
${license.split("\n").map((l) => ` * ${l}`.trimEnd()).join("\n")}
 */

import type { SVGProps } from "react";

type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function Icon({ size = 18, children, ...rest }: IconProps & { children: React.ReactNode }) {
  return (
    <svg width={size} height={size} viewBox="0 0 256 256" fill="currentColor" aria-hidden="true" focusable="false" {...rest}>
      {children}
    </svg>
  );
}

${body}`;
mkdirSync(join(here, "..", "src", "tools", "editor"), { recursive: true });
writeFileSync(join(here, "..", "src", "tools", "editor", "icons.tsx"), out);
console.log(`gen-editor-icons: ${Object.keys(ICONS).length} icons`);

