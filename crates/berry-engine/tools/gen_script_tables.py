"""Generates src/script_tables.rs: the small Unicode tables the engine's own text code needs
(marks, right-to-left letters, digits, scripts of complex-script text, presentation forms).

Compact on purpose: the default WebAssembly engine carries no general Unicode property crates.
Sources: Python's unicodedata (Unicode data, Unicode-3.0 licence) and fontTools.unicodedata
(MIT) for the Script property. Run: python3 tools/gen_script_tables.py > src/script_tables.rs
"""
import unicodedata as ud
from fontTools import unicodedata as ftu

SCRIPTS = [
    ("Latn", "Latin"), ("Deva", "Devanagari"), ("Beng", "Bengali"), ("Guru", "Gurmukhi"),
    ("Gujr", "Gujarati"), ("Orya", "Oriya"), ("Taml", "Tamil"), ("Telu", "Telugu"),
    ("Knda", "Kannada"), ("Mlym", "Malayalam"), ("Sinh", "Sinhala"), ("Arab", "Arabic"),
    ("Hebr", "Hebrew"), ("Syrc", "Syriac"), ("Thaa", "Thaana"), ("Thai", "Thai"), ("Laoo", "Lao"),
    ("Khmr", "Khmer"), ("Mymr", "Myanmar"), ("Tibt", "Tibetan"),
]
# Latin and Common are left out to keep the table small: they read as Other. The engine only
# needs to tell the complex scripts apart.
SCRIPTS = [s for s in SCRIPTS if s[0] != "Latn"]
NAMES = dict(SCRIPTS)


def ranges(pred, value=lambda c: True):
    out = []
    for cp in range(0x110000):
        c = chr(cp)
        v = value(c) if pred(c) else None
        if v is not None and out and out[-1][1] == cp - 1 and out[-1][2] == v:
            out[-1][1] = cp
        elif v is not None:
            out.append([cp, cp, v])
    return out


def emit(name, doc, rs, typ=None):
    print(f"/// {doc}")
    if typ:
        print(f"pub const {name}: &[(u32, u32, {typ})] = &[")
        for a, b, v in rs:
            print(f"    (0x{a:X}, 0x{b:X}, {typ}::{v}),")
    else:
        print(f"pub const {name}: &[(u32, u32)] = &[")
        for a, b, _ in rs:
            print(f"    (0x{a:X}, 0x{b:X}),")
    print("];\n")


print("//! Generated by tools/gen_script_tables.py from Unicode", ud.unidata_version,
      "data (Unicode-3.0 licence). Do not edit.")
print("#![allow(clippy::unreadable_literal)]\n")
print("use crate::script::Script;\n")
emit("NONSPACING_MARKS", "General categories Mn and Me.", ranges(lambda c: ud.category(c) in ("Mn", "Me")))
emit("SPACING_MARKS", "General category Mc.", ranges(lambda c: ud.category(c) == "Mc"))
emit("RTL", "Bidi classes R and AL.", ranges(lambda c: ud.bidirectional(c) in ("R", "AL")))
emit("DIGITS", "Bidi classes EN and AN.", ranges(lambda c: ud.bidirectional(c) in ("EN", "AN")))
emit("SCRIPTS", "Script property, for the scripts the engine treats specially (others: Other).",
     ranges(lambda c: ftu.script(c) in NAMES, lambda c: NAMES[ftu.script(c)]), "Script")

pres = []
for cp in list(range(0xFB1D, 0xFE00)) + list(range(0xFE70, 0xFF00)):
    d = ud.normalize("NFKC", chr(cp))
    if d != chr(cp) and d.strip():
        pres.append((cp, d))
text = "".join(d for _, d in pres)
print("/// Hebrew and Arabic presentation forms (U+FB1D–U+FEFF) and their NFKC text: (code point,")
print("/// start and end byte offsets in PRESENTATION_TEXT).")
print("pub const PRESENTATION: &[(u16, u16, u16)] = &[")
at = 0
for cp, d in pres:
    print(f"    (0x{cp:04X}, {at}, {at + len(d.encode('utf-8'))}),")
    at += len(d.encode("utf-8"))
print("];\n")
print("pub const PRESENTATION_TEXT: &str = \"" + "".join("\\u{%X}" % ord(c) for c in text) + "\";")
