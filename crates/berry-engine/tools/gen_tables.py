"""Generates src/tables.rs: base encodings, glyph-name → Unicode and standard-14 metrics.

Sources: reportlab (BSD) for the encodings and the core-14 AFM metrics, fontTools (MIT) for the
Adobe Glyph List (BSD-3-Clause). Run: python3 tools/gen_tables.py > src/tables.rs
"""
from fontTools import agl
from reportlab.pdfbase import _fontdata as f

names = dict(agl.AGL2UV)
legacy = getattr(agl, "LEGACY_AGL2UV", {})
encs = {
    "STANDARD": "StandardEncoding",
    "WIN_ANSI": "WinAnsiEncoding",
    "MAC_ROMAN": "MacRomanEncoding",
    "SYMBOL": "SymbolEncoding",
    "ZAPF_DINGBATS": "ZapfDingbatsEncoding",
}
used = set()
for e in encs.values():
    used.update(n for n in f.encodings[e] if n)
for font in f.widthsByFontGlyph.values():
    used.update(font)
for n in sorted(used):
    if n not in names:
        v = legacy.get(n)
        if v is None:
            u = agl.toUnicode(n)
            v = ord(u[0]) if u else None
        elif isinstance(v, (tuple, list)):
            v = v[0]
        if v:
            names[n] = v
# A few names producers use that the AGLFN lacks.
names.update({"nbspace": 0xA0, "sfthyphen": 0xAD, "middot": 0xB7, "Euro": 0x20AC, "space": 0x20})

print("// @generated by tools/gen_tables.py. Do not edit by hand.")
print("#![allow(clippy::all)]")
print()
print("/// Glyph name → Unicode scalar, sorted by name for binary search.")
print("pub static GLYPH_NAMES: &[(&str, u32)] = &[")
for n in sorted(names):
    print(f'    ("{n}", 0x{names[n]:04X}),')
print("];")
for const, e in encs.items():
    print()
    print(f"pub static {const}: [&str; 256] = [")
    row = list(f.encodings[e])
    if e == "WinAnsiEncoding":
        # reportlab fills the undefined codes with "bullet"; only 0x95 is the real one.
        row = [None if (n == "bullet" and j != 0x95) else n for j, n in enumerate(row)]
    for i in range(0, 256, 8):
        print("    " + " ".join(f'"{row[j] or ""}",' for j in range(i, i + 8)))
    print("];")
print()
print("/// Standard-14 metrics: (PostScript name, ascent, descent, glyph widths sorted by name).")
print("pub static STD14: &[(&str, i16, i16, &[(&str, u16)])] = &[")
for font, widths in f.widthsByFontGlyph.items():
    a, d = f.ascent_descent[font]
    print(f'    ("{font}", {a}, {d}, &[')
    items = sorted(widths.items())
    for i in range(0, len(items), 6):
        print("        " + " ".join(f'("{n}", {int(w)}),' for n, w in items[i : i + 6]))
    print("    ]),")
print("];")
