"""Generates src/presentation.rs: Hebrew and Arabic presentation forms folded to their NFKC text.

Some producers map Arabic glyphs to presentation forms (U+FExx) in ToUnicode. The editor shows and
edits the base letters. Source: Python's unicodedata (Unicode data, Unicode-3.0 licence).
Run: python3 tools/gen_presentation.py > src/presentation.rs
"""
import unicodedata as ud

print("//! Generated by tools/gen_presentation.py: Hebrew and Arabic presentation forms (U+FB1D–U+FEFF)")
print(f"//! to their NFKC text (Unicode {ud.unidata_version} data, Unicode-3.0 licence). Do not edit.")
print()
print("pub const PRESENTATION: &[(u32, &str)] = &[")
for cp in list(range(0xFB1D, 0xFE00)) + list(range(0xFE70, 0xFF00)):
    ch = chr(cp)
    d = ud.normalize("NFKC", ch)
    if d != ch and d.strip():
        print("    (0x%04X, \"%s\")," % (cp, "".join("\\u{%X}" % ord(c) for c in d)))
print("];")
